"""volume_extractor のユニットテスト"""
import pytest
from lib.volume_extractor import extract_volume_g


@pytest.mark.parametrize("text, expected", [
    # kg 系
    ("ふるさと牛タン 1.5kg ねぎ塩", 1500.0),
    ("コシヒカリ 5kg", 5000.0),
    ("牛肉 2,5kg 切り落とし", 2500.0),
    # g 系
    ("容量：国産牛肩ロース 約900g", 900.0),
    ("ホタテ 400g（訳あり）", 400.0),
    ("訳あり 1,000g 小分け", 1000.0),
    # 乗算
    ("ホタテ 500g×3パック", 1500.0),
    ("牛肉 250g×6", 1500.0),
    ("小分け 200g x2", 400.0),
    # 抽出不能
    (None, None),
    ("ふるさと納税 体験チケット", None),
    ("", None),
    # 大文字単位
    ("サーモン 800G", 800.0),
    ("米 4KG", 4000.0),
    # ─── v2 追加パターン ──────────────────────────────────────────────
    # Pattern 0: ラベル付き重量（最優先）
    ("内容量：900g の国産牛肩ロース", 900.0),
    ("合計1.5kgセット", 1500.0),
    ("正味量 500g スモークサーモン", 500.0),
    ("重量: 2,500g 訳あり品", 2500.0),
    ("容量 3kg 米セット", 3000.0),
    # Pattern 1: カウント先行パターン
    ("3袋 各500g 小分け", 1500.0),
    ("2パック×300g サーモン", 600.0),
    ("4個 500g いちご", 2000.0),
    ("6切れ 各200g 切り身", 1200.0),
    # Pattern 2: 単位あたり重量 × 個数
    ("250g/袋×4袋 小分け米", 1000.0),
    ("200g/パック × 3 鮭", 600.0),
    # Pattern 4: スペースなしカウント
    ("3袋500g 塩鮭", 1500.0),
    ("2パック300g ホタテ", 600.0),
])
def test_extract_volume_g(text, expected):
    result = extract_volume_g(text)
    if expected is None:
        assert result is None
    else:
        assert result == pytest.approx(expected)
